import { test, expect } from '@playwright/test';
import fs from 'node:fs';
for(const locale of ['en','ar']) test(locale+' displayed result follows replacement edits',async({page},info)=>{
 const call=async(body:any)=>{const r=await page.request.post('/api/v1/recommendation',{data:{locale,...body}});expect(r.ok()).toBeTruthy();return r.json();};
 const status=await call({op:'status'}), copy=status.copy;
 const v=await call({op:'start',path:'text',text:locale==='en'?'SUV from 1.2M to 1.5M, anything but Kia, low running costs':'عربية عالية من 1.2 مليون لـ 1.5 مليون، اي حاجه غير كيا، الأهم عندي البنزين'});
 const r=await call({op:'execute',brief:v.brief});
 await page.goto('/'+locale+'/find-my-car?r='+r.result.share.r);
 await expect(page.locator('.fmc-result')).toHaveAttribute('data-universe-version','U12-CEO3-R3-2026-11-04');
 await expect(page.locator('.fmc-result')).toHaveAttribute('data-result-id',r.result.result_id);
 await page.getByRole('button',{name:copy.r_edit,exact:true}).click();
 await expect(page.locator('.fmc-edit')).toBeVisible();
 // Remove the actual exclusion chip and every selected priority/check in the rendered edit form.
 await page.locator('.fmc-edit .chip').filter({hasText:'Kia'}).click();
 const priorityGroup=page.locator('.fmc-edit-grid > div').filter({has:page.locator('p').filter({hasText:copy.s_rows.priorities})});
 for(const chip of await priorityGroup.locator('button[aria-pressed="true"]').all()) await chip.click();
 const savedResponse=page.waitForResponse(r=>r.url().includes('/api/v1/recommendation')&&r.request().postDataJSON()?.op==='edit_save');
 await page.getByRole('button',{name:copy.e_save,exact:true}).click();
 const saved=await (await savedResponse).json();expect(saved.brief.brandsExclude).toEqual([]);expect(saved.brief.priorities).toEqual([]);
 expect(saved.brief.budgetMode).toBe('range');expect(saved.brief.budgetMin).toBe(1200000);
 const executed=page.waitForResponse(r=>r.url().includes('/api/v1/recommendation')&&r.request().postDataJSON()?.op==='execute');
 await page.locator('[data-fmc="confirm"]').click();
 const next=await (await executed).json();
 await expect(page.locator('.fmc-result')).toHaveAttribute('data-result-id',next.result.result_id);
 expect(next.result.result_id).not.toBe(r.result.result_id);
 const expected=await call({op:'execute',brief:saved.brief});expect(next.result).toEqual(expected.result);
 if(next.result.hero) await expect(page.locator('[data-model-id="'+next.result.hero.id+'"]').first()).toBeVisible();
 await expect(page.locator('.fmc')).toHaveAttribute('dir',locale==='ar'?'rtl':'ltr');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 fs.mkdirSync('ci-evidence/ceo3',{recursive:true});
 await page.screenshot({path:'ci-evidence/ceo3/'+locale+'-'+info.project.name+'.png',fullPage:true});
});
